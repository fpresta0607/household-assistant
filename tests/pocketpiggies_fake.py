def _now() -> datetime:
    return datetime.now(UTC)


@dataclass
class Seen:
    method: str
    path: str
    query: dict[str, list[str]]
    headers: dict[str, str]
    body: Any


@dataclass
class FakeState:
    base_url: str = ""
    requests: dict[str, dict[str, Any]] = field(default_factory=dict)
    grants: dict[str, dict[str, Any]] = field(default_factory=dict)
    seen: list[Seen] = field(default_factory=list)
    catalog: Any = field(default_factory=lambda: json.loads(json.dumps(CATALOG)))
    account_id: str = ACCOUNT
    is_revoke_failing: bool = False
    # A test sets this to answer every read with a fixed (status, body, headers).
    read_answer: tuple[int, Any, dict[str, str]] | None = None
    raw_answer: bytes | None = None
    # The plaid_items rows the records read returns, its page, and the status it answers.
    banks: list[dict[str, Any]] = field(default_factory=list)
    banks_page: dict[str, Any] = field(
        default_factory=lambda: {"limit": 500, "hasMore": False, "nextCursor": None}
    )
    banks_status: int = 200
    # Read paths that answer 503, so a test can fail the read after a sync.
    failing_paths: set[str] = field(default_factory=set)
    # What POST /api/assistant/sync answers. A synced answer marks every bank synced now.
    sync_answer: tuple[int, Any] = (200, {"status": "synced", "banksSynced": 1, "plaidCalls": 1})
    now: Callable[[], datetime] = _now

    def approve(self, request_id: str, *, decision: str = "approved") -> None:
        self.requests[request_id]["status"] = decision

    def live_grant(self, token: str) -> dict[str, Any] | None:
        grant = self.grants.get(token)
        return grant if grant is not None and not grant["revoked"] else None


class _Handler(BaseHTTPRequestHandler):
    state: FakeState

    def log_message(self, format: str, *args: object) -> None:
        return

    def _send(self, status: int, body: object, headers: dict[str, str] | None = None) -> None:
        raw = self.state.raw_answer or json.dumps(body).encode()
        self.send_response(status)
        self.send_header("Content-Type", "application/json")
        self.send_header("Content-Length", str(len(raw)))
        for key, value in (headers or {}).items():
            self.send_header(key, value)
        self.end_headers()
        self.wfile.write(raw)

    def _record(self) -> tuple[str, Any]:
        length = int(self.headers.get("Content-Length") or 0)
        body = json.loads(self.rfile.read(length)) if length else None
        url = urlsplit(self.path)
        self.state.seen.append(
            Seen(
                self.command,
                url.path,
                parse_qs(url.query),
                {key.lower(): value for key, value in self.headers.items()},
                body,
            )
        )
        return url.path, body

    def _bearer(self) -> str:
        return self.headers.get("Authorization", "").removeprefix("Bearer ")

    def do_GET(self) -> None:
        path, _ = self._record()
        self._read(path)

    def do_POST(self) -> None:
        path, body = self._record()
        if path.startswith("/api/assistant/link/"):
            self._link(path.rsplit("/", 1)[1], body)
        else:
            self._read(path)

    def _link(self, operation: str, body: dict[str, Any]) -> None:
        state = self.state
        if self._bearer() != CLIENT_CREDENTIAL:
            self._send(401, {"code": "invalid_client"})
            return
        bound = {key: body.get(key) for key in (*TELEGRAM_FIELDS, *HOUSEHOLD_FIELDS)}
        if bound not in (
            {**dict.fromkeys(HOUSEHOLD_FIELDS), **TELEGRAM_FIELDS},
            {**dict.fromkeys(TELEGRAM_FIELDS), **HOUSEHOLD_FIELDS},
        ):
            self._send(403, {"code": "invalid_binding"})
            return
        if operation == "requests":
            request_id = str(uuid.uuid4())
            state.requests[request_id] = {
                "challenge": body["codeChallenge"],
                "status": "pending",
                "expiresAt": _now() + timedelta(minutes=10),
            }
            self._send(
                201,
                {
                    "requestId": request_id,
                    "verificationUri": f"{state.base_url}/assistant/connect?request={request_id}",
                    "expiresAt": (_now() + timedelta(minutes=10)).isoformat(),
                },
            )
        elif operation == "exchange":
            request = state.requests.get(body.get("requestId", ""))
            if request is None:
                self._send(400, {"code": "invalid_request"})
                return
            digest = hashlib.sha256(body.get("codeVerifier", "").encode()).digest()
            if base64.urlsafe_b64encode(digest).rstrip(b"=").decode() != request["challenge"]:
                self._send(400, {"code": "invalid_request"})
            elif request["status"] in ("pending", "access_denied", "request_consumed"):
                code = (
                    "authorization_pending" if request["status"] == "pending" else request["status"]
                )
                self._send(400, {"code": code})
            else:
                request["status"] = "request_consumed"
                token = "ppa_ro_" + uuid.uuid4().hex + "A" * 11
                state.grants[token] = {"grantId": str(uuid.uuid4()), "revoked": False}
                self._send(
                    200,
                    {
                        "accessToken": token,
                        "tokenType": "Bearer",
                        "scope": "household:read",
                        "accountId": state.account_id,
                        "grantId": state.grants[token]["grantId"],
                        "expiresAt": (_now() + timedelta(days=180)).isoformat(),
                    },
                )
        elif operation == "revoke":
            if state.is_revoke_failing:
                self._send(503, {"code": "link_unavailable"})
                return
            for grant in state.grants.values():
                grant["revoked"] = True
            self._send(200, {"revoked": True})
        else:
            self._send(404, {})

    def _read(self, path: str) -> None:
        state = self.state
        if state.read_answer is not None:
            status, body, headers = state.read_answer
            self._send(status, body, headers)
            return
        if state.live_grant(self._bearer()) is None:
            self._send(401, {"error": {"code": "credential_rejected"}})
            return
        binding = tuple(
            self.headers.get(f"X-PocketPiggies-{name}")
            for name in (
                "Client-Id",
                "Telegram-User-Id",
                "Chat-Id",
                "Chat-Type",
                "Subject-Type",
                "Subject",
            )
        )
        if binding not in (
            ("corey", OWNER, OWNER, "private", None, None),
            # A household person's client, which PocketPiggies never lets be corey or denise.
            (HOUSEHOLD_CLIENT, None, None, None, "household_person", PERSON),
        ):
            self._send(403, {"code": "assistant_scope_denied"})
        elif path == "/api/assistant/catalog":
            self._send(200, state.catalog)
        elif path == "/api/assistant/sync":
            status, body = state.sync_answer
            if isinstance(body, dict) and body.get("status") == "synced":
                for bank in state.banks:
                    bank["last_sync_completed_at"] = state.now().isoformat().replace("+00:00", "Z")
            self._send(status, body)
        elif path == "/api/assistant/records/plaid_items" and state.banks_status != 200:
            self._send(state.banks_status, {"error": "refused", "code": "records_unavailable"})
        elif path == "/api/assistant/records/plaid_items":
            self._send(
                200,
                {
                    "schemaVersion": 1,
                    "table": "plaid_items",
                    "rows": state.banks,
                    "page": state.banks_page,
                },
            )
        elif path in state.failing_paths:
            self._send(503, {"error": "unavailable", "code": "read_unavailable"})
        elif path.startswith("/api/assistant/records/"):
            self._send(
                200,
                {
                    "schemaVersion": 1,
                    "table": path.rsplit("/", 1)[1],
                    "rows": [{"id": 1, "amount": "12.34", "date": "2026-09-30"}],
                    "page": {"limit": 100, "hasMore": False, "nextCursor": None},
                },
            )
        else:
            self._send(200, {"path": path, "safeCents": 4200})


@contextmanager
def fake_pocketpiggies() -> Iterator[FakeState]:
    state = FakeState()
    handler = type("Handler", (_Handler,), {"state": state})
    server = ThreadingHTTPServer(("127.0.0.1", 0), handler)
    state.base_url = f"http://127.0.0.1:{server.server_address[1]}"
    thread = threading.Thread(target=server.serve_forever, daemon=True)
    thread.start()
    try:
        yield state
    finally:
        server.shutdown()
        server.server_close()
        thread.join(timeout=5)
